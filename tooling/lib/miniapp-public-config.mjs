import { createHash } from "node:crypto";

const schemaVersion = "miniapp-public-build-config-v1";
const environments = new Set([
  "LOCAL",
  "CI",
  "DEV",
  "STAGING",
  "PRODUCTION",
  "MINIAPP_RUNNER",
]);
const localEnvironments = new Set(["LOCAL", "MINIAPP_RUNNER"]);
const localHostnames = new Set(["127.0.0.1", "localhost"]);
const expectedKeys = ["apiOrigin", "environment", "schemaVersion"];
const originPattern = /^(https?):\/\/([a-z0-9.-]+)(?::([0-9]{1,5}))?$/iu;

function fail(code) {
  throw new Error(code);
}

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function parseMiniappPublicConfig(value) {
  if (!isRecord(value)) {
    fail("MINIAPP_PUBLIC_CONFIG_OBJECT");
  }
  const keys = Object.keys(value).sort();
  if (
    keys.length !== expectedKeys.length ||
    keys.some((key, index) => key !== expectedKeys[index])
  ) {
    fail("MINIAPP_PUBLIC_CONFIG_CLOSED");
  }
  if (
    value.schemaVersion !== schemaVersion ||
    !environments.has(value.environment) ||
    typeof value.apiOrigin !== "string" ||
    value.apiOrigin.length > 200
  ) {
    fail("MINIAPP_PUBLIC_CONFIG_VALUE");
  }

  const match = originPattern.exec(value.apiOrigin);
  const scheme = match?.[1];
  const hostname = match?.[2]?.toLowerCase();
  const port = match?.[3];
  if (scheme === undefined || hostname === undefined) {
    fail("MINIAPP_PUBLIC_CONFIG_ORIGIN");
  }
  if (port !== undefined && (Number(port) < 1 || Number(port) > 65_535)) {
    fail("MINIAPP_PUBLIC_CONFIG_PORT");
  }
  if (scheme === "http") {
    if (
      !localEnvironments.has(value.environment) ||
      !localHostnames.has(hostname)
    ) {
      fail("MINIAPP_PUBLIC_CONFIG_TLS");
    }
  } else if (scheme !== "https") {
    fail("MINIAPP_PUBLIC_CONFIG_TLS");
  }

  return Object.freeze({
    apiOrigin: value.apiOrigin,
    environment: value.environment,
    schemaVersion: value.schemaVersion,
  });
}

export function miniappPublicConfigFingerprint(config) {
  const canonical = JSON.stringify({
    apiOrigin: config.apiOrigin,
    environment: config.environment,
    schemaVersion: config.schemaVersion,
  });
  return createHash("sha256").update(canonical).digest("hex");
}

export function normalizeGeneratedSourceLineEndings(value) {
  return value.replaceAll("\r\n", "\n");
}

export function renderMiniappPublicConfigSource(config) {
  const fingerprint = miniappPublicConfigFingerprint(config);
  return [
    "// @generated by tooling/build-miniapp.mjs; do not edit.",
    `// source-fingerprint: sha256:${fingerprint}`,
    "",
    'import type { PublicBuildConfigInput } from "../app/public-build-config.js";',
    "",
    "export const PUBLIC_BUILD_CONFIG: PublicBuildConfigInput = Object.freeze({",
    `  apiOrigin: ${JSON.stringify(config.apiOrigin)},`,
    `  environment: ${JSON.stringify(config.environment)},`,
    `  schemaVersion: ${JSON.stringify(config.schemaVersion)},`,
    "});",
    "",
  ].join("\n");
}

export function renderMiniappPublicConfigRuntime(config) {
  const fingerprint = miniappPublicConfigFingerprint(config);
  return [
    '"use strict";',
    "// @generated by tooling/build-miniapp.mjs; do not edit.",
    `// source-fingerprint: sha256:${fingerprint}`,
    'Object.defineProperty(exports, "__esModule", { value: true });',
    "exports.PUBLIC_BUILD_CONFIG = Object.freeze({",
    `  apiOrigin: ${JSON.stringify(config.apiOrigin)},`,
    `  environment: ${JSON.stringify(config.environment)},`,
    `  schemaVersion: ${JSON.stringify(config.schemaVersion)},`,
    "});",
    "",
  ].join("\n");
}
